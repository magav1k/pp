# Переменные-заглушки, значения зададим ниже
steps_in_part = 0      # ступенек в пролёте
floor = 0              # этаж проживания
total_seconds = 0      # итог в секундах

# Разделитель-шапка (\n — перевод строки)
print("\n==============\n")

# Описание программы
print("Данная программа считает на сколько увеличиться ваша жизнь при поднятии на этаж на котором вы живёте.")

# Отступ
print()

# Ввод: текст -> целое число
steps_in_part = int(input("Введите количество ступенек в пролёте: "))

# Отступ
print()

# Ввод этажа
floor = int(input("Введите этаж проживания: "))

# Отступ
print()

# Расчёт: ступеньки * 2 пролёта * этажи * 10 сек/ступеньку
total_seconds = steps_in_part * 2 * floor * 10

# Вывод результата через f-строку
print(f"Ваша жизнь при подянтии на: {floor} этаж продлиться на: {total_seconds} сек.")

# Закрывающий разделитель
print("\n==============\n")
